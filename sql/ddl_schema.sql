CREATE TABLE IF NOT EXISTS prontuario (
    id_prontuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(128) NOT NULL,
    historico_medico TEXT,
    alergias TEXT,
    observacoes TEXT,
    ultima_atualizacao TIMESTAMP,
    id_animal INTEGER NOT NULL UNIQUE REFERENCES animal (id_animal)  ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS cartao_vacina (
    id_vacina INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_vacina VARCHAR(100) NOT NULL,
    data_aplicacao DATE,
    numero_da_dose INTEGER,
    proxima_dose DATE,
    observacoes TEXT,
    id_animal INTEGER NOT NULL REFERENCES animal (id_animal) ON DELETE CASCADE,
    id_veterinario INTEGER NOT NULL REFERENCES veterinario (id_veterinario) ON DELETE CASCADE
);

