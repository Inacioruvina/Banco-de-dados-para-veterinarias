BEGIN;

CREATE TABLE IF NOT EXISTS clinicas (
    id_clinica INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(128) NOT NULL,
    endereco TEXT,
    telefone VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS clientes (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(128) NOT NULL,
    telefone VARCHAR(20),
    email VARCHAR(254) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS animais (
    id_animal INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(128) NOT NULL,
    especie VARCHAR(50) NOT NULL CHECK (especie IN ('Cão', 'Gato')),
    raca VARCHAR(50),
    data_nascimento DATE,
    id_cliente INTEGER NOT NULL REFERENCES clientes (id_cliente) ON DELETE CASCADE
);

-- Tabela temporária usada nos exemplos de ALTER e DROP.
CREATE TEMP TABLE exemplo_ddl (id INTEGER PRIMARY KEY, telefone VARCHAR(10));
ALTER TABLE exemplo_ddl ADD COLUMN email VARCHAR(254);
ALTER TABLE exemplo_ddl ALTER COLUMN telefone TYPE VARCHAR(20);
DROP TABLE IF EXISTS exemplo_ddl CASCADE;

COMMIT;
