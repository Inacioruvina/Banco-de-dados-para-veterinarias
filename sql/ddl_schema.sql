BEGIN;

CREATE TABLE IF NOT EXISTS clinica (
    id_clinica INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(128) NOT NULL,
    endereco TEXT NOT NULL,
    telefone VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS cliente (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(128) NOT NULL,
    telefone VARCHAR(20),
    email VARCHAR(254) UNIQUE
);

CREATE TABLE IF NOT EXISTS animal (
    id_animal INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(128) NOT NULL,
    especie VARCHAR(50) NOT NULL CHECK (especie IN ('Cao', 'Gato')),
    peso DECIMAL,
    raca VARCHAR(50),
    data_nascimento DATE,
    id_cliente INTEGER NOT NULL REFERENCES cliente (id_cliente) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS veterinario (
    id_veterinario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(128) NOT NULL,
    crmv VARCHAR(20) NOT NULL,
    telefone VARCHAR(20),
    especialidade VARCHAR(50),
    id_clinica INTEGER NOT NULL REFERENCES clinica (id_clinica) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS consulta (
    id_consulta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_de_atendimento DATE NOT NULL,
    horario TIME WITHOUT TIME ZONE NOT NULL,
    motivo TEXT,
    diagnostico TEXT,
    observacoes TEXT,
    id_animal INTEGER NOT NULL REFERENCES animal (id_animal) ON DELETE CASCADE,
    id_veterinario INTEGER NOT NULL REFERENCES veterinario (id_veterinario) ON DELETE CASCADE,
    id_clinica INTEGER NOT NULL REFERENCES clinica (id_clinica) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS medicamento (
    id_medicamento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR (128) NOT NULL,
    dosagem VARCHAR (100) NOT NULL,
    id_consulta INTEGER NOT NULL REFERENCES consulta (id_consulta) ON DELETE CASCADE
);

